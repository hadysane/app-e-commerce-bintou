function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="fr">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();

  useEffect(() => {
    const { data } = supabase.auth.onAuthStateChange((event) => {
      if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
      void router.invalidate();
      if (event !== "SIGNED_OUT") void queryClient.invalidateQueries();
      // Return to the page requested before signing in (e.g. from an email confirmation link).
      if (event === "SIGNED_IN") {
        const next = sessionStorage.getItem("bintou-after-login");
        if (next) {
          sessionStorage.removeItem("bintou-after-login");
          void router.navigate({ to: next });
        } else if (window.location.pathname === "/auth") {
          void router.navigate({ to: "/admin" });
        }
      }
    });
    return () => data.subscription.unsubscribe();
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      <CartProvider>
        <div className="flex min-h-screen flex-col">
          <SiteHeader />
          <main className="flex-1">
            {/* Required: nested routes render here. */}
            <Outlet />
          </main>
          <SiteFooter />
        </div>
        <CartSheet />
        <Toaster position="bottom-center" />
      </CartProvider>
    </QueryClientProvider>
  );
}
